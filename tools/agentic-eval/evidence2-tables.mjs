// tools/agentic-eval/evidence2-tables.mjs (WO-C16) -- mechanical Evidence2 results tables: no
// hand-transcribed numbers. Reuses campaign-summary.mjs's own summarizeCampaign/fmtRate/fmtStats/
// fmtProvenanceLine and readme-evidence.mjs's own disjointTokens/sessionCost/armCostRange/
// scalarMetric/compositionMedians/tokenCompositionMedians/commandKindAggregate -- never re-derives
// any of that logic, so these tables and the metrics-grid/scorecard can never silently disagree
// about the same number.
//
// Produces 5 Markdown sections (per-cell detail, runtime x arm aggregates, sensitivity, provenance
// and controls, cost) and inserts them between <!-- evidence2-tables:start/end --> markers in a
// target doc, in --write/--check modes mirroring readme-evidence.mjs's own CLI convention.
//
// Usage:
//   node tools/agentic-eval/evidence2-tables.mjs <campaign-dir> <target-doc> [options]
//     --cost-estimate <path>   cost-estimate.json (schema 2); omit for "not recorded" cost columns
//     --infra-flake <path>     infra-flake-classifier.mjs's own output; omit for "not classified"
//     --write                  write the target doc in place (default: check, exit 1 on mismatch)

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { summarizeCampaign, fmtRate, fmtStats, fmtProvenanceLine } from './campaign-summary.mjs';
import {
  disjointTokens, sessionCost, armCostRange, scalarMetric, compositionMedians,
  tokenCompositionMedians, commandKindAggregate, TOKEN_COMPONENT_TYPES, TOKEN_COMPONENT_LABEL,
  COMMAND_KIND_LABEL,
} from './readme-evidence.mjs';

// The full first line the generated block starts with, vs. the bare prefix used to FIND that line
// in an existing doc (readme-evidence.mjs's own main() does the same split: a `startMarker` prefix
// for searching, the full descriptive comment only appears in the generated block itself).
export const EVIDENCE2_TABLES_START = '<!-- evidence2-tables:start (generated by tools/agentic-eval/evidence2-tables.mjs -- edit the generator, not this block) -->';
const EVIDENCE2_TABLES_START_PREFIX = '<!-- evidence2-tables:start';
export const EVIDENCE2_TABLES_END = '<!-- evidence2-tables:end -->';

const RUNTIME_ORDER = ['claude-code', 'codex-cli'];
const ARM_ORDER = ['product', 'free'];

function findGroup(summary, runtimeId, arm) {
  return summary.by_runtime_arm.find((g) => g.runtime_id === runtimeId && g.arm === arm);
}

function fmtYesNo(v) {
  return v === null || v === undefined ? 'n/a' : v ? 'yes' : 'no';
}

function fmtStatus(cell) {
  if (cell.status === 'accepted') return 'accepted';
  if (cell.status === 'negative-d3') return `negative (D3)${cell.reason ? `: ${cell.reason}` : ''}`;
  if (cell.status === 'missing') return `missing: ${cell.reason ?? 'unknown'}`;
  return cell.status ?? 'unknown';
}

function fmtCommandKindCounts(counts) {
  if (!counts) return 'n/a';
  return `${COMMAND_KIND_LABEL.kmp_test} ${counts.kmp_test}, ${COMMAND_KIND_LABEL.gradle} ${counts.gradle}, ${COMMAND_KIND_LABEL.other} ${counts.other}`;
}

// Same runtime-specific disjoint mapping the grid uses (WO-C13) -- a Codex cell only shows
// "reasoning" when reasoning_output is genuinely tracked (WO-C13 residual), never a fabricated 0.
function fmtDisjointTokens(tokens, runtimeId) {
  if (!tokens) return 'n/a';
  const d = disjointTokens(tokens, runtimeId);
  const types = TOKEN_COMPONENT_TYPES[runtimeId].filter((t) => d[t] !== undefined);
  return types.map((t) => `${TOKEN_COMPONENT_LABEL[t]} ${d[t]}`).join(', ');
}

// The one matching cost-estimate.json cell for a specific campaign-summary cell (arm + round_index
// == order_index) -- costMetric() in readme-evidence.mjs operates arm-wide (every cell in the arm at
// once); this narrows that same lookup to a single cell for the per-cell table.
function costEstimateCellEntry(costEstimate, runtimeId, arm, roundIndex) {
  if (!costEstimate) return null;
  if (costEstimate.schema === 1 && runtimeId === 'claude-code') {
    return costEstimate.cells.find((c) => c.runtime_id === 'claude-code' && c.arm === arm && c.order_index === roundIndex) ?? null;
  }
  if (costEstimate.schema === 2 && costEstimate.runtimes?.[runtimeId]) {
    return costEstimate.runtimes[runtimeId].cells.find((c) => c.arm === arm && c.order_index === roundIndex) ?? null;
  }
  return null;
}

// Midpoint of the low(5m)/high(1h) estimate for ONE cell, the same low/high assumptions and
// uncached_input_may_be_cache_writes handling as readme-evidence.mjs's own costMetric -- never a
// separately-invented single-price estimate for the same cell.
function costEstimateCellMidpoint(costEstimate, runtimeId, entry) {
  const price = costEstimate.schema === 1 ? costEstimate.pricing.per_million_tokens : costEstimate.runtimes[runtimeId].per_million_tokens;
  const uncachedMayBeCacheWrites = costEstimate.schema === 2 && costEstimate.runtimes[runtimeId].uncached_input_may_be_cache_writes === true;
  const highInputPrice = uncachedMayBeCacheWrites ? Math.max(price.cache_write_5m, price.cache_write_1h) : price.input;
  const low = sessionCost(entry.tokens, price, 'cache_write_5m');
  const high = sessionCost(entry.tokens, price, 'cache_write_1h', highInputPrice);
  return (low + high) / 2;
}

function fmtCellCost(cell, costEstimate) {
  if (typeof cell.total_cost_usd === 'number') return `$${cell.total_cost_usd.toFixed(4)} (provider-reported)`;
  const entry = costEstimateCellEntry(costEstimate, cell.runtime_id, cell.arm, cell.round_index);
  if (!entry) return 'not recorded';
  const mid = costEstimateCellMidpoint(costEstimate, cell.runtime_id, entry);
  return `$${mid.toFixed(4)} (estimate: midpoint of low/high)`;
}

function fmtInfraFlake(cellKey, infraFlakeByCellKey) {
  if (!infraFlakeByCellKey) return 'not classified';
  const v = infraFlakeByCellKey.get(cellKey);
  return v === undefined ? 'not classified' : String(v);
}

// ---------------------------------------------------------------------------
// (a) Per-cell table

export function buildPerCellTableLines(summary, costEstimate, infraFlakeResult) {
  const infraFlakeByCellKey = infraFlakeResult ? new Map(infraFlakeResult.cells.map((c) => [c.cell_key, c.infra_flake_suspected])) : null;
  const lines = [
    '| runtime | arm | round | status | key facts | full answer | success | duration ms | tool calls | shell commands | tokens | turns | cost | infra-flake |',
    '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|',
  ];
  for (const c of summary.cells) {
    lines.push([
      '', c.runtime_id, c.arm ?? 'unknown', c.round_index, fmtStatus(c),
      fmtYesNo(c.key_facts_match), fmtYesNo(c.full_answer_match),
      c.arm === 'product' ? fmtYesNo(c.success) : 'n/a',
      c.duration_ms ?? 'n/a', c.tool_calls_total ?? 'n/a',
      fmtCommandKindCounts(c.command_kind_counts),
      fmtDisjointTokens(c.tokens, c.runtime_id),
      c.num_turns ?? 'n/a',
      fmtCellCost(c, costEstimate),
      fmtInfraFlake(c.cell_key, infraFlakeByCellKey),
      '',
    ].join(' | '));
  }
  return lines;
}

// ---------------------------------------------------------------------------
// (b)/(c) Runtime x arm aggregates -- reused verbatim for the primary and the sensitivity summary
// (the auditor's own "the same aggregates" instruction), so the two can never silently diverge in
// shape.

// Turns has no group-level aggregate in campaign-summary.mjs's own output (unlike duration_ms/
// tool_calls_total/shell_commands_total) -- computed directly from summary.cells here, same
// median/min/max shape fmtStats expects, never a hand-picked number.
function turnsStats(summary, runtimeId, arm) {
  const values = summary.cells
    .filter((c) => c.runtime_id === runtimeId && c.arm === arm && typeof c.num_turns === 'number')
    .map((c) => c.num_turns);
  if (values.length === 0) return { n: 0 };
  const sorted = [...values].sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  const median = sorted.length % 2 === 1 ? sorted[mid] : (sorted[mid - 1] + sorted[mid]) / 2;
  return { n: sorted.length, median, min: sorted[0], max: sorted[sorted.length - 1] };
}

function fmtCompositionMedians(comp) {
  if (!comp) return 'not recorded';
  return comp.segments.map((s) => `${s.type} ${s.value}`).join(', ');
}

export function buildAggregateTableLines(summary) {
  const lines = [
    '| runtime | arm | key facts | full answer | success (product only) | duration ms | tool calls | shell commands by kind (median) | tokens by type (median) | turns |',
    '|---|---|---|---|---|---|---|---|---|---|',
  ];
  for (const g of summary.by_runtime_arm) {
    const shellComp = compositionMedians(summary, g, g.runtime_id, g.arm, 'command_kind_counts', ['kmp_test', 'gradle', 'other'], commandKindAggregate);
    const tokenComp = tokenCompositionMedians(summary, g, g.runtime_id, g.arm);
    const turns = turnsStats(summary, g.runtime_id, g.arm);
    lines.push([
      '', g.runtime_id, g.arm,
      fmtRate(g.key_facts_match), fmtRate(g.full_answer_match),
      g.success ? fmtRate(g.success) : 'n/a',
      fmtStats(g.duration_ms), fmtStats(g.tool_calls_total),
      fmtCompositionMedians(shellComp), fmtCompositionMedians(tokenComp),
      fmtStats(turns),
      '',
    ].join(' | '));
  }
  return lines;
}

// ---------------------------------------------------------------------------
// (c) Sensitivity

export function buildSensitivityLines(sensitivitySummary, excludedCellKeys) {
  const lines = ['### Sensitivity (infra-flake-suspected cells excluded)', ''];
  lines.push(excludedCellKeys.length === 0 ? 'Excluded cells: none.' : `Excluded cells: ${excludedCellKeys.join(', ')}.`);
  lines.push('');
  if (sensitivitySummary.summary_status !== 'ok') {
    lines.push(`Refused: \`${sensitivitySummary.reason_code}\`.`);
    return lines;
  }
  lines.push(...buildAggregateTableLines(sensitivitySummary));
  return lines;
}

// ---------------------------------------------------------------------------
// (d) Provenance and controls -- every fmtProvenanceLine call mirrors campaign-summary.mjs's own
// renderMarkdown Provenance section exactly (reuses the same helper), plus reasoning_effort_source
// (WO-C16's own addition to buildProvenance) that renderMarkdown didn't carry before this file existed.

export function buildProvenanceLines(summary) {
  const p = summary.provenance;
  const lines = ['### Provenance and controls', ''];
  lines.push(fmtProvenanceLine('repo_commit', p.repo_commit));
  lines.push(fmtProvenanceLine('skill_source_sha', p.skill_source_sha));
  lines.push(fmtProvenanceLine('kmp_test_cli_version', p.kmp_test_cli_version));
  lines.push(fmtProvenanceLine('kmp_test_cli_source_sha', p.kmp_test_cli_source_sha));
  for (const runtimeId of RUNTIME_ORDER) {
    lines.push(fmtProvenanceLine(`${runtimeId} CLI version`, p.runtime_cli_version[runtimeId]));
    lines.push(fmtProvenanceLine(`${runtimeId} model_resolved`, p.model_resolved[runtimeId]));
    lines.push(fmtProvenanceLine(`${runtimeId} reasoning_effort (requested)`, p.reasoning_effort[runtimeId]));
    lines.push(fmtProvenanceLine(`${runtimeId} reasoning_effort_source`, p.reasoning_effort_source[runtimeId]));
  }
  return lines;
}

// ---------------------------------------------------------------------------
// (e) Cost -- low/high per runtime x arm (armCostRange, the same range the scorecard's cost bar and
// costMetric's own per-session estimate are built from) plus the pricing source/date each runtime's
// cost-estimate.json entry carries.

function fmtCostRangeRow(low, high) {
  return `$${low.toFixed(4)}–$${high.toFixed(4)}`;
}

export function buildCostLines(costEstimate) {
  const lines = ['### Cost', ''];
  if (!costEstimate) {
    lines.push('Not recorded: no cost-estimate.json for this campaign.');
    return lines;
  }
  lines.push('| runtime | arm | low | high | pricing source | retrieved |');
  lines.push('|---|---|---|---|---|---|');
  for (const runtimeId of RUNTIME_ORDER) {
    const entry = costEstimate.schema === 2
      ? costEstimate.runtimes?.[runtimeId]
      : (runtimeId === 'claude-code' ? { per_million_tokens: costEstimate.pricing.per_million_tokens, cells: costEstimate.cells.filter((c) => c.runtime_id === 'claude-code'), source: costEstimate.pricing.source, retrieved: costEstimate.pricing.retrieved } : null);
    if (!entry) {
      lines.push(['', runtimeId, '(all)', 'not recorded', 'not recorded', 'not recorded', 'not recorded', ''].join(' | '));
      continue;
    }
    for (const arm of ARM_ORDER) {
      const cells = entry.cells.filter((c) => c.arm === arm);
      if (cells.length === 0) {
        lines.push(['', runtimeId, arm, 'not recorded', 'not recorded', entry.source ?? 'not recorded', entry.retrieved ?? 'not recorded', ''].join(' | '));
        continue;
      }
      const { low, high } = armCostRange(cells, entry.per_million_tokens, entry.uncached_input_may_be_cache_writes === true);
      lines.push(['', runtimeId, arm, `$${low.toFixed(4)}`, `$${high.toFixed(4)}`, entry.source ?? 'not recorded', entry.retrieved ?? 'not recorded', ''].join(' | '));
    }
  }
  return lines;
}

// ---------------------------------------------------------------------------
// Assembly

export function renderEvidence2TablesBlock(summary, costEstimate, infraFlakeResult, sensitivitySummary, excludedCellKeys) {
  const lines = [EVIDENCE2_TABLES_START, ''];
  lines.push('## Evidence2 results (mechanically generated -- do not hand-edit; see evidence2-tables.mjs)');
  lines.push('');
  if (summary.summary_status !== 'ok') {
    lines.push(`Refused: \`${summary.reason_code}\`.`);
    lines.push('', EVIDENCE2_TABLES_END);
    return lines.join('\n');
  }
  lines.push(`Campaign: \`${summary.campaign_id}\`. Scenario: \`${summary.scenario_id}\`.`);
  lines.push('');
  lines.push('### Per-cell detail', '');
  lines.push(...buildPerCellTableLines(summary, costEstimate, infraFlakeResult));
  lines.push('');
  lines.push('### Runtime × arm aggregates', '');
  lines.push(...buildAggregateTableLines(summary));
  lines.push('');
  lines.push(...buildSensitivityLines(sensitivitySummary, excludedCellKeys));
  lines.push('');
  lines.push(...buildProvenanceLines(summary));
  lines.push('');
  lines.push(...buildCostLines(costEstimate));
  lines.push('', EVIDENCE2_TABLES_END);
  return lines.join('\n');
}

// One-call orchestration: real campaign dir + already-loaded cost-estimate/infra-flake docs (or
// null for either -- every section degrades to "not recorded"/"not classified", never a crash or a
// fabricated figure) -> the full block. Runs summarizeCampaign TWICE (primary, then sensitivity with
// the infra-flake-suspected cells excluded) so the sensitivity table is the real thing, not a
// filtered copy of the primary one's rows.
export function buildEvidence2TablesFromCampaign(campaignDir, costEstimate, infraFlakeResult) {
  const summary = summarizeCampaign(campaignDir);
  const excludedCellKeys = infraFlakeResult
    ? infraFlakeResult.cells.filter((c) => c.infra_flake_suspected === true).map((c) => c.cell_key)
    : [];
  const sensitivitySummary = summarizeCampaign(campaignDir, new Set(excludedCellKeys));
  return renderEvidence2TablesBlock(summary, costEstimate, infraFlakeResult, sensitivitySummary, excludedCellKeys);
}

export function insertBetweenMarkers(docText, block) {
  const startIdx = docText.indexOf(EVIDENCE2_TABLES_START_PREFIX);
  const endIdx = docText.indexOf(EVIDENCE2_TABLES_END);
  if (startIdx === -1 || endIdx === -1) return null;
  const before = docText.slice(0, startIdx);
  const after = docText.slice(endIdx + EVIDENCE2_TABLES_END.length);
  return before + block + after;
}

// ---------------------------------------------------------------------------
// CLI

function main(argv) {
  const positional = argv.filter((a) => !a.startsWith('--'));
  const campaignDir = positional[0];
  const targetDoc = positional[1];
  const mode = argv.includes('--write') ? 'write' : 'check';
  const costEstimateIdx = argv.indexOf('--cost-estimate');
  const costEstimatePath = costEstimateIdx >= 0 ? argv[costEstimateIdx + 1] : null;
  const infraFlakeIdx = argv.indexOf('--infra-flake');
  const infraFlakePath = infraFlakeIdx >= 0 ? argv[infraFlakeIdx + 1] : null;

  if (!campaignDir || !existsSync(campaignDir) || !targetDoc) {
    console.error('usage: evidence2-tables.mjs <campaign-dir> <target-doc> [--cost-estimate <path>] [--infra-flake <path>] [--write]');
    return 1;
  }
  const costEstimate = costEstimatePath && existsSync(costEstimatePath) ? JSON.parse(readFileSync(costEstimatePath, 'utf8')) : null;
  const infraFlakeResult = infraFlakePath && existsSync(infraFlakePath) ? JSON.parse(readFileSync(infraFlakePath, 'utf8')) : null;

  const block = buildEvidence2TablesFromCampaign(campaignDir, costEstimate, infraFlakeResult);

  if (mode === 'write') {
    if (!existsSync(targetDoc)) {
      console.error(`::error::${targetDoc} does not exist -- create it with the evidence2-tables:start/end markers first`);
      return 1;
    }
    const doc = readFileSync(targetDoc, 'utf8');
    const updated = insertBetweenMarkers(doc, block);
    if (updated === null) {
      console.error(`::error::${targetDoc} is missing the evidence2-tables:start/end markers`);
      return 1;
    }
    writeFileSync(targetDoc, updated);
    console.log(`Updated ${targetDoc}`);
    return 0;
  }

  // check mode: regenerate and diff against what's committed
  const doc = existsSync(targetDoc) ? readFileSync(targetDoc, 'utf8') : '';
  const startIdx = doc.indexOf(EVIDENCE2_TABLES_START_PREFIX);
  const endIdx = doc.indexOf(EVIDENCE2_TABLES_END);
  if (startIdx === -1 || endIdx === -1 || doc.slice(startIdx, endIdx + EVIDENCE2_TABLES_END.length) !== block) {
    console.error(`::error::out of date, run with --write: ${targetDoc}`);
    return 1;
  }
  console.log('Evidence2 tables are up to date.');
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
